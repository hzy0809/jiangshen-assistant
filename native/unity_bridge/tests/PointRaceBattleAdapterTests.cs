using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using UnityEngine;
using JiangShen.AssistantRuntime;
using D = JiangShen.AssistantRuntime.SharedDevelopmentContext;

// Detached replay of an existing PointRace scene. The production adapter and
// settlement are compiled intact; only Unity, transport and stock UI are fake.
internal static partial class PointRaceBattleAdapterTests
{
    private const string Operation = "00000000000000000000000000000042";
    private static int checks;
    private static void Check(bool value, string why)
    { checks++; if (!value) throw new Exception(why); }
    private static string Q(string value) { return Command.Quote(value); }
    // Fixed wire frames: result=0, iswin, embedded report=(opponent 271,
    // report 987), gold_consume=0, idother=271. These are not generated by
    // the production reader or the fixture's protobuf serializer.
    private static byte[] Receipt(bool win)
    { return BattleReplyPreflightWire.Point(271, 271, 987, 0, win); }

    private sealed class Fixture
    {
        internal readonly RootMessenger Home, Scene, BattleRoot;
        internal readonly RootUI GlobalUi;
        internal readonly ArenaSelectUI Select;
        internal readonly PointraceUI Race;
        internal readonly BattleUI Battle;
        internal readonly BattleNormalResultUI Result;
        internal readonly game.net.tcp_client Client;
        internal readonly DailyPointRaceModel Model;
        internal readonly BattleSettlement Owner;
        internal readonly UnityEngine.Object[] All;
        internal bool Paused;
        internal bool EntryFromHome;
        private int sequence;

        internal Fixture()
        {
            typeof(BattleSettlement).GetField("active", BindingFlags.Static | BindingFlags.NonPublic).SetValue(null, null);
            BattleLaunch.Reset();
            GameObject.Paths.Clear(); BattleFixtureTrace.Events.Clear(); Global.Templates.Clear();
            Global.character_ = new Database.Character { next_resource_time = 150000 };
            Global.character_.pointrace.challengers.Add(new PointRaceChallenger());
            Global.relogin = false; Global.extern_enabled = true;
            TimeUtil._now = 106400; TimeUtil._thisDay = 86400; RootUI.m_bRefreshFive = false;
            Client = new game.net.tcp_client(); RootUI.m_client = Global.m_client = Client;
            game.net.tcp_base.connection_state = 3;
            Home = new RootMessenger { LevelID = "Campaign" }; Home.gameObject.Attach(Home);
            GlobalUi = Home.gameObject.Attach(new RootUI { rmg = Home });
            Home.gameObject.Attach(new MainUI { rmg = Home });
            Select = Home.gameObject.Attach(new ArenaSelectUI { rmg = Home, enabled = false });
            Scene = new RootMessenger { LevelID = "PointRace" }; Scene.gameObject.Attach(Scene);
            GlobalUi.level_rmg = Scene; BaseUI.rootUI = GlobalUi;
            Race = new PointraceUI { rmg = Scene, m_pointrace = Global.character_.pointrace, enabled = true };
            Race.transform.parent = Scene.transform; Race.gameObject.Attach(Race);
            GameObject.Paths["/PointRace"] = Scene.gameObject;
            GameObject.Paths["/PointRace/PointRaceUI"] = Race.gameObject;
            BattleRoot = new RootMessenger { LevelID = "Battle" }; BattleRoot.gameObject.Attach(BattleRoot);
            GameObject.Paths["/Battle"] = BattleRoot.gameObject;
            Battle = new BattleUI { rmg = BattleRoot, m_prevUI = Scene, enabled = false };
            Battle.transform.parent = BattleRoot.transform; Battle.gameObject.Attach(Battle);
            Result = Battle.gameObject.Attach(new BattleNormalResultUI { rmg = BattleRoot, battle_ui = Battle, enabled = false });
            GameObject.Paths["/Battle/BattleUI"] = Battle.gameObject;
            BattleModeFixtureObjects.Battle = Battle; BattleModeFixtureObjects.Result = Result; BattleModeFixtureObjects.PointRace = Race;
            BaseAsset.lds = new Loader { currmg = Scene, oldmainrmg = Home, isBattling = false, enabled = false };
            MainUI.m_subui = null; __BaseUI.battle_result_ui = null;
            All = new UnityEngine.Object[] { Home, GlobalUi, Select, Scene, Race, Battle, Result };
            Model = new DailyPointRaceModel();
            Owner = new BattleSettlement(delegate(string name, string fields) { }, delegate { return !Paused; });
        }
        internal D Context()
        { return new D(All, EntryFromHome ? Home : Scene, GlobalUi, Global.character_, "78", "PASS", Paused, delegate { return null; }); }
        internal void Capture() { Model.Capture(Context()); }
        internal int Revision()
        { return (int)typeof(DailyPointRaceModel).GetField("revision", BindingFlags.NonPublic | BindingFlags.Instance).GetValue(Model); }
        internal void Action(string action, bool expected = true)
        {
            string why;
            Check(Model.Queue(109, 78, Operation, ++sequence, Revision(), action, out why), "queue " + action + ": " + why + " " + Model.Json());
            bool actual = Model.ExecuteGui(Context, delegate { }, delegate(DailyPointRaceInvocationCheck sample, DailyPointRaceInvocationCheck check)
                { return !Paused && sample() && check(); }, out why);
            Check(actual == expected, "execute " + action + ": " + why + " " + Model.Json());
        }
        internal game.net.tcp_base.Handler Start()
        {
            Capture(); Action("resume"); Capture(); Action("challenge");
            Check(Client.Sent.Count == 1 && Client.Sent[0] == 0x465, "resume uses existing scene and starts exactly one free challenge");
            Check(BattleLaunch.DirectCalls == 1 && BattleLaunch.FormationCalls == 0 && BattleLaunch.CheckCalls == 1 &&
                BattleLaunch.Last != null && BattleLaunch.Last.Mode == BattleMode.PointRace && BattleLaunch.Last.Opcode == 0x465 &&
                ReferenceEquals(BattleLaunch.Last.Source, Race) && ReferenceEquals(BattleLaunch.Last.Target, Global.character_.pointrace.challengers[0]),
                "actual PointRace challenge passes its exact scene, opponent and opcode to guard substitute");
            return (game.net.tcp_base.Handler)Client.m_handlers[(ushort)0x465];
        }
        internal void FinishAndReturnToScene(bool win)
        {
            Client.Dispatch(0x465, Receipt(win));
            Check(BattleLaunch.Last.InitialCalls == 1 && ReferenceEquals(BattleLaunch.Last.InitialBattle, Battle) &&
                ReferenceEquals(BattleLaunch.Last.InitialReport, Battle.interpreter.m_report), "PointRace forwards exact stock report to guard substitute once");
            Capture(); Action("skip");
            Check(BattleLaunch.ReportBoundCalls == 1 && ReferenceEquals(BattleLaunch.LastOwnership.Source, Race) &&
                ReferenceEquals(BattleLaunch.LastOwnership.Target, Global.character_.pointrace.challengers[0]), "PointRace settlement binds the same owner and opponent to guard substitute");
            Capture(); Action("battle_close");
            Check(Client.Sent.Count == 2 && Client.Sent[1] == 0x464, "stock exit starts one list refresh on the original scene");
            Client.Dispatch(0x464, new byte[] { 8, 0 }); Capture();
        }
        internal bool CanQueue(string action)
        {
            string why;
            return Model.Queue(109, 78, Operation, ++sequence, Revision(), action, out why);
        }
    }

    private static void WinPreservesScene()
    {
        Fixture f = new Fixture(); f.Start(); f.FinishAndReturnToScene(true);
        Check(f.Race.Applied == 1 && Global.character_.pointrace.challenge_count == 1 &&
            ((PointRaceChallenger)Global.character_.pointrace.challengers[0]).killed, "win updates the stock account and target once");
        Check(f.Battle.OpenCalls == 1 && f.Battle.ExitCalls == 1 && f.Race.Returns == 1 &&
            ReferenceEquals(BaseAsset.lds.currmg, f.Scene) && !BaseAsset.lds.isBattling, "result and stock callback return to the original PointRace scene once");
        Check(f.Client.EndRequests == 0 && !f.Client.Sent.Contains(0x408) && f.Race.EntryCalls == 1,
            "already-settled PointRace refreshes its list without requesting 0x408");
        Check(f.Model.Json().Contains("\"challenges_completed\":1") && f.Model.Json().Contains("\"next_action\":\"return\""),
            "confirmed round is counted once and no eligible opponent leads to return");
    }
    private static void LossCanContinueOnce()
    {
        Fixture f = new Fixture(); f.Start(); f.FinishAndReturnToScene(false);
        Check(f.Race.Applied == 1 && Global.character_.pointrace.challenge_count == 1 &&
            !((PointRaceChallenger)Global.character_.pointrace.challengers[0]).killed, "loss preserves the uncompleted target and counts one attempt");
        Check(f.Model.Json().Contains("\"won\":false") && f.Model.Json().Contains("\"challenges_completed\":1") &&
            f.Model.Json().Contains("\"next_action\":\"challenge\""), "next challenge is offered only after list refresh and completed stock callback");
        Check(f.Client.Sent.Count == 2 && f.Client.EndRequests == 0 && f.Battle.OpenCalls == 1 && f.Race.Returns == 1,
            "observations do not issue a second challenge or duplicate presentation");
    }
    private static void DuplicateFailsClosed()
    {
        Fixture f = new Fixture(); game.net.tcp_base.Handler pending = f.Start();
        DevelopmentNormalCallback retained = pending.handler;
        f.Client.Dispatch(0x465, Receipt(true)); retained(new MemoryStream(Receipt(true), false), null); f.Capture();
        Check(f.Model.Json().Contains("\"status\":\"UNKNOWN\"") && f.Race.Applied == 1 &&
            Global.character_.pointrace.challenge_count == 1, "duplicate reply is unknown and stock account update runs only once");
        Check(!f.CanQueue("skip") && !f.CanQueue("challenge") && f.Client.Sent.Count == 1 && f.Battle.OpenCalls == 0,
            "unknown duplicate cannot open or launch another fight");
    }
    private static void TimeoutFailsClosed()
    {
        Fixture f = new Fixture(); f.Start(); f.Client.Dispatch(0x465, null); f.Capture(); f.Capture();
        Check(f.Model.Json().Contains("\"status\":\"UNKNOWN\"") && f.Race.Applied == 0 && f.Race.CallbackCalls == 0,
            "timeout is unknown before the stock callback");
        Check(!f.CanQueue("challenge") && !f.CanQueue("skip") && f.Client.Sent.Count == 1 && f.Client.EndRequests == 0,
            "timeout cannot be replayed or converted into settlement");
    }
    private static void RejectFailsClosed()
    {
        Fixture f = new Fixture(); f.Start(); f.Client.Dispatch(0x465, new byte[] { 8, 1 }); f.Capture();
        Check(f.Model.Json().Contains("\"status\":\"UNKNOWN\"") && f.Model.Json().Contains("pointrace_server_rejected_cleanup_unresolved") &&
            f.Race.Applied == 0, "server rejection remains unknown while stock loading cleanup is unresolved");
        Check(!f.CanQueue("challenge") && !f.CanQueue("skip") && f.Client.Sent.Count == 1 && f.Battle.OpenCalls == 0,
            "rejected request cannot start a second fight");
    }
    private static void SameIdReplacementFailsClosed()
    {
        Fixture f = new Fixture(); f.Start(); Global.character_.pointrace.challengers[0] = new PointRaceChallenger();
        f.Client.Dispatch(0x465, Receipt(true)); f.Capture();
        Check(f.Model.Json().Contains("\"status\":\"UNKNOWN\"") && f.Race.Applied == 0 &&
            Global.character_.pointrace.challenge_count == 0, "same-ID target replacement is detected before stock callback");
        Check(!f.CanQueue("challenge") && f.Battle.OpenCalls == 0 && f.Race.Returns == 0,
            "replacement cannot cause new fight or foreign page return");
    }
    private static void WrongCallbackTargetFailsClosed()
    {
        Fixture f = new Fixture(); f.Start(); f.Client.Dispatch(0x465, Receipt(true));
        PointraceUI stranger = new PointraceUI(); f.Battle.OnClose = stranger.BattleClose; f.Capture();
        Check(!f.Model.Json().Contains("\"next_action\":\"skip\"") && !f.CanQueue("skip"),
            "another PointRace instance cannot own this report");
        Check(f.Battle.OpenCalls == 0 && f.Race.Returns == 0 && stranger.Returns == 0 && f.Client.EndRequests == 0,
            "foreign return callback is untouched");
    }
    private static void StopDoesNotLaunchAgain()
    {
        Fixture f = new Fixture(); game.net.tcp_base.Handler pending = f.Start();
        DevelopmentNormalCallback retained = pending.handler; f.Model.Stop();
        f.Client.Dispatch(0x465, Receipt(true)); retained(new MemoryStream(Receipt(true), false), null); f.Capture();
        Check(!f.CanQueue("challenge") && !f.CanQueue("skip") && f.Client.Sent.Count == 1,
            "stopped owner cannot issue another challenge or present");
        Check(f.Race.CallbackCalls == 1 && f.Race.Applied == 1 && f.Battle.OpenCalls == 0 && f.Race.Returns == 0,
            "normal stop applies only the already-sent native response once without automation");
    }
    private static void GuardDenialDoesNotCallStock()
    {
        Fixture f = new Fixture(); f.Capture(); f.Action("resume"); f.Capture();
        BattleLaunch.ForceDeny = true; f.Action("challenge", false); f.Capture();
        Check(BattleLaunch.DirectCalls == 1 && f.Client.Sent.Count == 0 && f.Race.CallbackCalls == 0 &&
            f.Model.Json().Contains("\"status\":\"UNKNOWN\""), "denied direct guard prevents stock challenge and stays unresolved");
        Check(!f.CanQueue("challenge") && !f.CanQueue("skip"), "denied guard cannot replay or present");
    }

    private static int Main()
    {
        KeyValuePair<string, Action>[] cases = {
            new KeyValuePair<string, Action>("pointrace_reply_wrong_opponent_blocked", PointReplyWrongOpponent),
            new KeyValuePair<string, Action>("pointrace_reply_premium_blocked", PointReplyPremium),
            new KeyValuePair<string, Action>("pointrace_reply_wire_and_identity_negatives", PointReplyNegatives),
            new KeyValuePair<string, Action>("pointrace_reply_original_stream_and_defaults", PointReplyValidVariants),
            new KeyValuePair<string, Action>("pointrace_reply_report_mutation_unknown", PointReplyReportMutation),
            new KeyValuePair<string, Action>("pointrace_win_settled_original_scene", WinPreservesScene),
            new KeyValuePair<string, Action>("pointrace_loss_then_natural_next", LossCanContinueOnce),
            new KeyValuePair<string, Action>("pointrace_duplicate_unknown", DuplicateFailsClosed),
            new KeyValuePair<string, Action>("pointrace_timeout_unknown", TimeoutFailsClosed),
            new KeyValuePair<string, Action>("pointrace_rejection_unknown", RejectFailsClosed),
            new KeyValuePair<string, Action>("pointrace_replaced_target_unknown", SameIdReplacementFailsClosed),
            new KeyValuePair<string, Action>("pointrace_foreign_callback_blocks", WrongCallbackTargetFailsClosed),
            new KeyValuePair<string, Action>("pointrace_stop_pending", StopDoesNotLaunchAgain),
            new KeyValuePair<string, Action>("pointrace_guard_denial_no_stock_start", GuardDenialDoesNotCallStock)
            ,new KeyValuePair<string, Action>("pointrace_entry_callback_distinct_wait", EntryCallbackDistinctWait)
            ,new KeyValuePair<string, Action>("pointrace_entry_timeout_stock_cleanup_unknown", EntryTimeoutSafeReturn)
            ,new KeyValuePair<string, Action>("pointrace_entry_timeout_return_safety_negatives", EntryTimeoutSafetyNegatives)
            ,new KeyValuePair<string, Action>("pointrace_entry_timeout_queued_return_rechecked", EntryTimeoutReturnRechecked)
            ,new KeyValuePair<string, Action>("pointrace_entry_timeout_stop_pause_win", EntryTimeoutStopPause)
            ,new KeyValuePair<string, Action>("pointrace_entry_timeout_late_native_callback", EntryTimeoutLateCallback)
            ,new KeyValuePair<string, Action>("pointrace_entry_timeout_incomplete_return", EntryTimeoutIncompleteReturn)
            ,new KeyValuePair<string, Action>("pointrace_entry_callback_normal_path", EntryCallbackNormalPath)
        };
        int failed = 0;
        foreach (KeyValuePair<string, Action> test in cases)
        {
            int before = checks;
            try { test.Value(); Console.WriteLine("{\"scenario\":" + Q(test.Key) + ",\"status\":\"PASS\",\"checks\":" + (checks - before) + "}"); }
            catch (Exception error)
            {
                failed++;
                while (error is TargetInvocationException && error.InnerException != null) error = error.InnerException;
                Console.WriteLine("{\"scenario\":" + Q(test.Key) + ",\"status\":\"FAIL\",\"error\":" + Q(error.ToString()) + "}");
            }
        }
        Console.WriteLine("{\"status\":" + Q(failed == 0 ? "PASS" : "FAIL") + ",\"scenarios\":" + cases.Length +
            ",\"failed\":" + failed + ",\"checks\":" + checks +
            ",\"scope\":\"production PointRace adapter and settlement; fake client/Unity and instrumented launch-guard substitute; no actual IPC or guard race\",\"game_access\":false}");
        return failed == 0 ? 0 : 1;
    }
}
